#[allow(clippy::too_many_arguments)]
pub fn etf_fixture(
    symbol: &str,
    name: &str,
    underlying_index: &str,
    nav: Decimal,
    premium_discount_pct: Decimal,
    aum_cr: Decimal,
    expense_ratio: Decimal,
    tracking_error: Decimal,
    return_1y: Decimal,
    volume: u64,
) -> ScreenerEtfRecord {
    let ltp = nav + nav * premium_discount_pct / dec!(100);
    ScreenerEtfRecord {
        symbol: symbol.to_string(),
        name: name.to_string(),
        underlying_index: underlying_index.to_string(),
        nav,
        ltp,
        premium_discount_pct,
        aum_cr,
        expense_ratio,
        tracking_error,
        return_1y,
        volume,
    }
}

