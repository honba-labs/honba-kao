/// Tagged union over every asset class, in fixture order.
pub fn universe_for(asset: ScreenerAssetType) -> Vec<ScreenerRecord> {
    match asset {
        ScreenerAssetType::Stocks => stock_universe()
            .into_iter()
            .map(ScreenerRecord::Stock)
            .collect(),
        ScreenerAssetType::Etf => etf_fixtures()
            .into_iter()
            .map(ScreenerRecord::Etf)
            .collect(),
        ScreenerAssetType::Bonds => bond_fixtures()
            .into_iter()
            .map(ScreenerRecord::Bond)
            .collect(),
        ScreenerAssetType::MutualFunds => {
            mf_fixtures().into_iter().map(ScreenerRecord::Mf).collect()
        }
    }
}
