use rust_decimal::Decimal;
use rust_decimal_macros::dec;

use super::types::ScreenerEquityRecord;

/// Builds a screener row from the supplied dimensions; derived metrics
/// (`change`, `rvol`, `turnover_cr`) are computed exactly, and every field
/// not passed in is zeroed / defaulted.
#[allow(clippy::too_many_arguments)]
pub fn equity_fixture(
    symbol: &str,
    name: &str,
    exchange: &str,
    sector: &str,
    industry: &str,
    market_cap_category: &str,
    is_fno: bool,
    is_watchlist: bool,
    price: Decimal,
    change_pct: Decimal,
    volume: u64,
    avg_volume_20d: u64,
    pe_ratio: Decimal,
    dividend_yield: Decimal,
    roe: Decimal,
    market_cap_cr: Decimal,
    day_low: Decimal,
    day_high: Decimal,
    low_52w: Decimal,
    high_52w: Decimal,
    rsi_14: Decimal,
) -> ScreenerEquityRecord {
    let change = price * change_pct / dec!(100);
    let rvol = Decimal::from(volume) / Decimal::from(avg_volume_20d);
    let turnover_cr = price * Decimal::from(volume) / dec!(10_000_000);

    ScreenerEquityRecord {
        symbol: symbol.to_string(),
        name: name.to_string(),
        exchange: exchange.to_string(),
        sector: sector.to_string(),
        industry: industry.to_string(),
        market_cap_category: market_cap_category.to_string(),
        is_fno,
        is_watchlist,
        price,
        change,
        change_pct,
        volume,
        avg_volume_20d,
        rvol,
        turnover_cr,
        day_low,
        day_high,
        high_52w,
        low_52w,
        return_1d: change_pct,
        return_1w: dec!(0),
        return_1m: dec!(0),
        return_3m: dec!(0),
        return_6m: dec!(0),
        return_ytd: dec!(0),
        return_1y: dec!(0),
        return_3y: dec!(0),
        rsi_14,
        macd_line: dec!(0),
        macd_signal: dec!(0),
        macd_hist: dec!(0),
        sma_20: dec!(0),
        sma_50: dec!(0),
        sma_200: dec!(0),
        ema_9: dec!(0),
        ema_21: dec!(0),
        atr_14: dec!(0),
        atr_pct: dec!(0),
        bb_upper: dec!(0),
        bb_lower: dec!(0),
        bb_bandwidth: dec!(0),
        supertrend_direction: 0,
        market_cap_cr,
        pe_ratio,
        forward_pe: dec!(0),
        pb_ratio: dec!(0),
        ps_ratio: dec!(0),
        ev_ebitda: dec!(0),
        peg_ratio: dec!(0),
        dividend_yield,
        dividend_per_share: dec!(0),
        payout_ratio: dec!(0),
        roe,
        roce: dec!(0),
        operating_margin: dec!(0),
        net_margin: dec!(0),
        debt_to_equity: dec!(0),
        current_ratio: dec!(0),
        interest_coverage: dec!(0),
        revenue_cr: dec!(0),
        revenue_growth_yoy: dec!(0),
        net_profit_cr: dec!(0),
        eps: dec!(0),
        fcf_cr: dec!(0),
        book_value_per_share: dec!(0),
    }
}

